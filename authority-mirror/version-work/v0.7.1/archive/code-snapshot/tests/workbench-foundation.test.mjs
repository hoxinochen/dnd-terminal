import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = path => readFile(new URL(path, import.meta.url), 'utf8');
const css = await read('../src/workbench-foundation.css');
const themes = await read('../src/battle-workbench.css');
const app = await read('../src/app.js');
const html = await read('../index.html');
assert.ok(html.indexOf('workbench-foundation.css') > html.indexOf('src/styles.css'));
assert.match(themes, /html\[data-theme="light"\] \{/);
assert.match(themes, /html\[data-theme="parchment"\] \{/);
assert.match(app, /function render\(\)\{\s*document.documentElement.dataset.theme/);
assert.match(css, /--wb-muted: var\(--wb-text-secondary\)/);
assert.match(css, /@container workbench \(max-width: 620px\)/);
assert.doesNotMatch(themes, /@media \(max-width: 960px\)/);
assert.match(css, /\.wb-col-right \.economy-grid \{ grid-template-columns: minmax\(0,1fr\)/);
assert.match(css, /\.range-target-picker/);
assert.match(css, /\.reinforcements-panel/);
assert.match(css, /\.wb-map-canvas \.wb-token \{ position: absolute/);
assert.match(themes, /--wb-bg-surface: #f2f4f5/);
assert.match(themes, /--wb-bg-canvas: #c9ae82/);
assert.match(app, /data-range-target/);
assert.match(app, /场外预备与增援/);
console.log('workbench foundation contracts: pass (visual acceptance remains browser-based)');
